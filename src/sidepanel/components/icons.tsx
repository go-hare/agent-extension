import type { SVGProps } from 'react';

export type IconProps = {
  size?: number | string;
  className?: string;
  color?: string;
  /** lucide-compat no-ops so call sites can keep passing them */
  strokeWidth?: number | string;
  absoluteStrokeWidth?: boolean;
  title?: string;
} & Omit<SVGProps<SVGSVGElement>, 'color' | 'strokeWidth'>;

/** Component type used by toolDisplay etc. (replaces LucideIcon). */
export type LucideIcon = (props: IconProps) => React.ReactElement;

/** Official size → vectorSize map (IconBase `I` / `Te`). */
const SIZE_MAP: Record<number, number> = {
  12: 16,
  14: 16,
  16: 20,
  20: 20,
  24: 24,
  28: 28,
  32: 32,
};

function num(size: number | string | undefined, fallback: number): number {
  if (typeof size === 'number') return size;
  if (typeof size === 'string') {
    const n = Number(size);
    return Number.isFinite(n) ? n : fallback;
  }
  return fallback;
}

/**
 * Official IconBase `I` / `Te` (mcpPermissions → sidepanel):
 *   vectorSize = vectorSizeOverride ?? SIZE_MAP[size]
 *   svg always gets className + flexShrink:0
 *   if no override → wrap in sized flex div that ALSO gets className
 */
function IconBase({
  size = 20,
  className,
  color = 'currentColor',
  viewBox = '0 0 20 20',
  vectorSizeOverride,
  alt,
  children,
  ...rest
}: IconProps & {
  viewBox?: string;
  vectorSizeOverride?: number;
  alt?: string;
  children: React.ReactNode;
}) {
  const cssSize = num(size, 20);
  const vectorSize = vectorSizeOverride ?? SIZE_MAP[cssSize] ?? cssSize;
  const {
    strokeWidth: _sw,
    absoluteStrokeWidth: _asw,
    title: _title,
    ...svgRest
  } = rest;

  const svg = (
    <svg
      width={vectorSize}
      height={vectorSize}
      viewBox={viewBox}
      fill={color}
      xmlns="http://www.w3.org/2000/svg"
      style={{ flexShrink: 0 }}
      className={className}
      aria-label={alt}
      aria-hidden={!alt}
      {...svgRest}
    >
      {children}
    </svg>
  );

  // Official: vectorSizeOverride → bare svg; else sized wrapper div.
  if (vectorSizeOverride != null) return svg;

  return (
    <div
      className={className}
      style={{
        width: cssSize,
        height: cssSize,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
      }}
    >
      {svg}
    </div>
  );
}

function fillIcon(d: string, displayName: string): LucideIcon {
  const Comp = (props: IconProps) => (
    <IconBase {...props}>
      <path d={d} />
    </IconBase>
  );
  Comp.displayName = displayName;
  return Comp;
}

